import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import sharp from 'sharp';

const root = fileURLToPath(new URL('../', import.meta.url));
const config = JSON.parse(await readFile(join(root, 'assets/branding/app-icon.json'), 'utf8'));
const source = await readFile(join(root, 'assets/branding/material-symbols-lyrics.svg'), 'utf8');
const viewBox = source.match(/viewBox="([^"]+)"/)?.[1];
const paths = [...source.matchAll(/<path\s+d="([^"]+)"\s*\/>/g)];
assert.equal(viewBox, '0 -960 960 960');
assert.equal(paths.length, 1, 'the pinned Material Symbols SVG has exactly one path');
assert.match(config.purple, /^#[0-9a-f]{6}$/i);
assert.match(config.pwaBackground, /^#[0-9a-f]{6}$/i);
const path = paths[0][1];
const glyph = (size) => `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="${viewBox}"><path fill="${config.purple}" d="${path}"/></svg>\n`;

function tile(size, kind) {
  // Android's entire foreground fits inside the central 40%-radius circle.
  // Apple receives an opaque square and applies its own corner mask.
  const fraction = kind === 'maskable' ? .56 : .72;
  const inset = size * (1 - fraction) / 2;
  const glyphSize = size * fraction;
  const radius = kind === 'any' ? size * .22 : 0;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}"><rect width="${size}" height="${size}" rx="${radius}" fill="${config.pwaBackground}"/><svg x="${inset}" y="${inset}" width="${glyphSize}" height="${glyphSize}" viewBox="${viewBox}"><path fill="${config.purple}" d="${path}"/></svg></svg>`;
}

async function png(svg, opaque = false) {
  let image = sharp(Buffer.from(svg));
  if (opaque) image = image.flatten({ background: config.pwaBackground });
  return image.png({ compressionLevel: 9, adaptiveFiltering: false, palette: false }).toBuffer();
}

function ico(frames) {
  const header = Buffer.alloc(6 + frames.length * 16);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(frames.length, 4);
  let offset = header.length;
  for (let i = 0; i < frames.length; i++) {
    const { size, data } = frames[i];
    const at = 6 + i * 16;
    header[at] = header[at + 1] = size === 256 ? 0 : size;
    header.writeUInt16LE(1, at + 4);
    header.writeUInt16LE(32, at + 6);
    header.writeUInt32LE(data.length, at + 8);
    header.writeUInt32LE(offset, at + 12);
    offset += data.length;
  }
  return Buffer.concat([header, ...frames.map(frame => frame.data)]);
}

const outputs = new Map();
outputs.set('public/icon.svg', Buffer.from(glyph(24)));
const license = await readFile(join(root, 'assets/branding/LICENSE.material-symbols'), 'utf8');
outputs.set('public/icon-LICENSE.txt', Buffer.from(`Material Symbols Outlined / lyrics by Google. Apache-2.0.\nSource: https://github.com/google/material-design-icons/tree/${config.sourceCommit}\nAdapted for Lyrics Note: brand color and platform-specific sizing/surfaces.\n\n${license}`));
for (const size of [16, 32]) outputs.set(`public/icon-${size}x${size}.png`, await png(glyph(size)));
for (const size of [192, 512]) outputs.set(`public/icon-${size}x${size}.png`, await png(tile(size, 'any')));
outputs.set('public/icon-maskable-512x512.png', await png(tile(512, 'maskable'), true));
outputs.set('public/apple-touch-icon.png', await png(tile(180, 'apple'), true));
const frames = await Promise.all([16, 32, 48, 64, 128, 256].map(async size => ({ size, data: await png(glyph(size)) })));
outputs.set('src/app/favicon.ico', ico(frames));
const quote = value => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
outputs.set('src/lib/app-icon.ts', Buffer.from([
  '// Generated by scripts/generate-app-icons.mjs from the pinned Google Material Symbols SVG.',
  `export const APP_ICON_REVISION = ${quote(config.revision)};`,
  `export const APP_ICON_COLOR = ${quote(config.purple)};`,
  `export const APP_ICON_VIEW_BOX = ${quote(viewBox)};`,
  `export const APP_ICON_PATH = ${quote(path)};`,
  '',
].join('\n')));

const check = process.argv.includes('--check');
for (const [file, bytes] of outputs) {
  const target = join(root, file);
  if (check) {
    assert.deepEqual(await readFile(target), bytes, `${file} is stale; run npm run icons:generate`);
  } else {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, bytes);
  }
}
console.log(JSON.stringify({ mode: check ? 'verified' : 'generated', revision: config.revision, purple: config.purple, files: [...outputs.keys()] }));
